// Package reports provides the model of the audit reports produced by the
// auditor.
//
// A Report holds the findings of an audit, the description of what has been
// analyzed, and the lifecycle status of the analysis that produced it. The
// reports are attached to the modules, the packages and the code entries, and
// they are serialized with the elements that carry them.
package reports

import (
	audsts "github.com/nabbar/auditor/pkg/data/status"
)

// Report represents a self-contained audit report.
//
// A report encapsulates the diagnostic findings of a specific component or of
// a specific area of the system. It is the primary data structure for the
// tracking and the management of the analytical results, throughout their
// lifecycle.
//
// Fields:
//   - Name: the unique identifier of the report.
//   - Content: the detailed and human readable results of the analysis.
//   - Status: the current processing state of the report.
type Report struct {
	// Name is a unique identifier that clearly describes the report's origin, purpose, or scope.
	// It should be descriptive enough to enable easy categorization and cross-referencing
	// of different report types within the audit system. This field is used as a key identifier
	// for report tracking and management.
	Name string

	// Content contains the detailed, human-readable results of the diagnostic analysis.
	// It is typically generated by diagnostic components and may include:
	// - Summary of findings
	// - Technical analysis
	// - Recommendations for improvement
	// - Severity indicators
	// The content is stored in Markdown format to enable easy rendering and visualization.
	Content string

	// Status tracks the current processing state of the report, indicating whether it is
	// pending, completed, or encountered an error. This field enables real-time monitoring
	// and management of the audit workflow, ensuring that reports are properly tracked
	// throughout their processing stages.
	Status audsts.Status
}
