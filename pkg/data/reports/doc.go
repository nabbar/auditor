// Package reports provides the model of the audit reports produced by the
// auditor.
//
// A Report encapsulates the diagnostic findings of a specific component or
// area of the system. It is the primary data structure for tracking and
// managing analytical results throughout their lifecycle.
//
// The Report type does not expose any methods of its own; it is a plain data
// structure. The lifecycle, access, and management of reports are handled
// by the container element (Module, Package, or Entry) through the Data[M]
// contract that every data-layer model implements. Each container exposes
// SetReports, GetReports, and LstReports, which operate on an internal
// map[string]Report indexed by the report's Name field.
//
// # The Report struct
//
// Report is the only exported type of this package. It holds three fields:
//
//   - Name: a descriptive string that uniquely identifies the report. It is
//     used as the key in the container's internal map, so it must be unique
//     within the container context. A good Name should describe the report's
//     origin, purpose, or scope (for example "security_findings_module_x").
//
//   - Content: a string containing the detailed, human-readable results of
//     the analysis. It is typically in Markdown format to allow easy
//     rendering by consumer applications. The content may include summaries,
//     technical analysis, recommendations, severity indicators, and any
//     other structured or free-form text generated by the audit component.
//
//   - Status: an audsts.Status value (from pkg/data/status) that tracks the
//     processing state of the element that owns this report, reflecting which
//     audit phases have completed (Audited1 through Audited4, plus the
//     earlier Parsed, Vendor, and Analyzed phases).
//
// # Data layer integration
//
// Reports are not stored or queried through this package. They are embedded
// inside the three container models of the data layer:
//
//   - Module (mod): map[string]Report stored as Rep in the serialized
//     representation, accessible via mod.Mdl.SetReports, GetReports, LstReports.
//
//   - Package (pkg): map[string]Report stored as Rep, accessible via
//     pkg.Mdl.SetReports, GetReports, LstReports.
//
//   - Entry (entry): map[string]Report stored as Rep, accessible via
//     entry.Mdl.SetReports, GetReports, LstReports.
//
// All three container types embed the Data[M] generic interface, which
// declares the SetReports(audrep.Report), GetReports(string) audrep.Report,
// and LstReports() []audrep.Report methods.
//
// # Data flow
//
// The flow of a report through the auditor follows the audit pipeline:
//
//   1. Discovery: the parser discovers code elements and creates Module, Package,
//      and Entry instances with Status = None.
//
//   2. Analysis: the AST is parsed (Parsed bit), vendor resolution may occur
//      (Vendor bit), and the summary is computed (Analyzed bit).
//
//   3. Audit: one or more audit components run against the element and produce
//      Report instances. Each component writes its findings by calling
//      SetReports(Report) with a unique Name. The Status field of the container
//      is advanced to the corresponding phase bit (Audited1, Audited2, etc.).
//
//   4. Retrieval: consumers read the reports through GetReports(name) for a
//      specific report or LstReports() to get all reports of a container.
//
//   5. Serialization: when the container is serialized to json, yaml, toml, or
//      cbor, the report map is marshaled under the "reports" field, and the
//      Status uint8 is serialized as its raw numeric value for lossless
//      round-tripping.
//
// Usage example:
//
//   // Create a report with a human-readable name and Markdown content.
//   r := reports.Report{
//       Name:    "security_audit",
//       Content: "# Security Audit\n\n3 findings...",
//       Status:  status.Audited1,
//   }
//
//   // Attach it to a module (or package, or entry).
//   modInstance.SetReports(r)
//
//   // Retrieve a specific report by name.
//   specific := modInstance.GetReports("security_audit")
//
//   // Retrieve all reports of the module.
//   all := modInstance.LstReports()
