// Package entry provides the model of the code elements handled by the
// auditor.
//
// An Entry represents a single code element: a function, a method, a type,
// a variable or a constant. It holds the name of the element, the identifier
// of the package that contains it, the code type, the type string that
// qualifies it, the source code with its language identifier, the input and
// output parameters, the identifiers of the elements it depends on, its
// lifecycle status, a user-defined summary, and the reports generated by the
// audit.
//
// # Data model
//
// The Entry interface extends the generic auddat.Data[Entry] contract, which
// provides a shared foundation for identity, status, summary, equality,
// reports, and serialization. On top of this base, Entry adds accessors and
// mutators specific to a code element.
//
// The concrete implementation of Entry is the unexported mdl struct. A caller
// never uses it directly: it is returned by the New and Empty constructors and
// accessed only through the Entry interface.
//
// # Resolution of the package and of the dependencies
//
// The containing package and the dependencies are not stored as objects, but as
// identifiers. They are resolved on demand through the resolvers that are
// registered with RegisterGetPackage and RegisterGetEntry.
//
// RegisterGetPackage registers a function that maps an audids.ID to an
// audpkg.Package. It is required by the New constructor (to look up the
// package and derive the entry identifier) and by the GetPkg accessor. When
// no resolver has been registered, these calls panic.
//
// RegisterGetEntry registers a function that maps an audids.ID to an Entry.
// It is used by GetDepend to resolve the identifiers that describe the
// dependencies of an entry. When no resolver has been registered, GetDepend
// panics. Both resolvers are package-level variables, written once during
// application initialization; they are not protected by any mutex.
//
// # Serialization
//
// Entry supports JSON, YAML, TOML, and CBOR serialization and deserialization.
// The intermediate representation used by all formats is the public Export
// struct. During marshaling, the internal state is copied into an Export
// instance, which is then handed to the format-specific marshaler. During
// unmarshaling, the serialized data is decoded into an Export instance, which
// is then applied back to the internal state.
//
// The MarshalBinary and UnmarshalBinary methods (encoding.BinaryMarshaler /
// encoding.BinaryUnmarshaler) are implemented on top of the CBOR format,
// providing the binary format required by the standard library.
//
// # Thread safety
//
// The mdl model is protected by a sync.RWMutex. All read accessors use
// RLock/RUnlock and all write accessors use Lock/Unlock. The entry is safe
// for concurrent use. However, GetInputs and GetOutputs return the internal
// slices by reference: the caller must not modify them, and a concurrent
// modification may race with their use. GetDependIds returns a copy, so it
// is safe to modify.
//
// # Lifecycle and status
//
// Each entry carries a bit-field status (see the status sub-package) that
// tracks the completion of processing phases:
//
//     bit 0  - Parsed    : AST parsing has completed.
//     bit 1  - Vendor    : AST vendor resolution has completed.
//     bit 2  - Analyzed  : Summary analysis has completed.
//     bit 3  - Audited1  : First audit report is generated.
//     bit 4  - Audited2  : Second audit report is generated.
//     bit 5  - Audited3  : Third audit report is generated.
//     bit 6  - Audited4  : Fourth audit report is generated.
//     bit 7  - Outdated  : The entry has been flagged as out of date.
//
// The status is managed through dedicated setters (SetStatusParsed, etc.),
// clearers (UnSetStatusParsed, etc.), and query methods (IsStatusParsed,
// etc.). The zero value means that no phase is active.
//
// # Equality and merge
//
// IsEqual performs a deep comparison between two entries: it compares their
// ID, package ID, name, type string, input and output parameters, dependencies,
// vendor status, and source content. The comparison is content-based, not
// identity-based: two entries built independently from the same coordinates but
// holding different data are reported as different.
//
// Merge updates an entry with the data of another entry of the same identity.
// It is used to refresh a stored entry with a freshly parsed version of the
// same element. Empty fields in the source are never transferred: they do not
// overwrite the data already held by the receiver. Merge returns false when
// the two entries do not designate the same element.
//
// # Data flow
//
// The processing of a code entry follows this flow:
//
//     ┌─────────────┐
//     │  Parser     │  reads source code, recognizes entry types
//     └──────┬──────┘
//            │ creates
//            ▼
//     ┌─────────────┐
//     │  New()      │  initializes the entry with package ID, name,
//     └──────┬──────┘    code type, type string, source code, language
//            │
//            ▼
//     ┌─────────────┐
//     │  Status     │  SetStatusParsed is called
//     └──────┬──────┘
//            │
//            ▼
//     ┌─────────────┐
//     │  Vendor     │  vendor resolution; params and dependencies
//     │  Resolution │  are populated through AddInputs, AddOutputs,
//     └──────┬──────┘    AddDepend; SetStatusVendor is called
//            │
//            ▼
//     ┌─────────────┐
//     │  Analysis   │  summary is generated via SetSummary;
//     └──────┬──────┘    SetStatusAnalyzed is called
//            │
//            ▼
//     ┌─────────────┐
//     │  Audit      │  audit reports are added via SetReports;
//     │  (1 to 4)   │    SetStatusAudited1..4 are called
//     └──────┬──────┘
//            │
//            ▼
//     ┌─────────────┐
//     │  Merge /    │  when the source is re-parsed, Merge folds
//     │  Refresh    │  the new data into the existing entry;
//     └──────┬──────┘    SetStatusOutdated is called if needed
//            │
//            ▼
//     ┌─────────────┐
//     │  Serialize  │  Export struct + format marshaler
//     └─────────────┘
//
// # Public API
//
// The following public API is provided by this package:
//
//   Types:
//     - Entry           : the interface that represents a code element.
//     - FuncEnt         : a factory function type that creates new Entry instances.
//     - Export          : the intermediate struct used during serialization.
//   Constructors:
//     - New(id, name, typeStr, codeType, lang, src) : creates a fully initialized entry.
//     - Empty()                                     : creates an entry with all zero fields.
//   Resolvers:
//     - RegisterGetPackage(f)                       : registers the package resolver.
//     - RegisterGetEntry(f)                         : registers the entry resolver.
//   Package and identity:
//     - GetPkg()                                    : returns the resolved Package.
//     - GetPkgId()                                  : returns the identifier of the containing package.
//     - GetName()                                   : returns the name of the code element.
//     - GetFullPath()                               : returns the full path (package + name).
//     - GetID()                                     : returns the unique identifier of the entry.
//     - Empty()                                     : returns true if the entry is incomplete.
//     - IsEqual(f)                                  : deep comparison with another Entry.
//     - GetParentId()                               : returns the identifier of the containing package.
//   Type:
//     - SetType(c, s)                               : sets the code type and type string.
//     - GetType()                                   : returns the code type and type string.
//     - GetTypeString()                             : returns a formatted string representation.
//     - IsVendor()                                  : returns true if the containing package is vendor.
//   Source:
//     - GetSource()                                 : returns the associated Source.
//     - GetLang()                                   : returns the language identifier.
//   Parameters:
//     - GetInputs()                                 : returns the input parameters slice.
//     - AddInputs(p ...)                            : appends input parameters.
//     - DelInputs()                                 : clears all input parameters.
//     - GetOutputs()                                : returns the output parameters slice.
//     - AddOutputs(p ...)                           : appends output parameters.
//     - DelOutputs()                                : clears all output parameters.
//   Dependencies:
//     - GetDepend()                                 : returns the resolved dependency entries.
//     - GetDependIds()                              : returns the copy of the dependency IDs.
//     - AddDepend(id ...)                           : adds dependency identifiers.
//     - DelDepend(id ...)                           : removes specific or all dependencies.
//   Status (Set / UnSet / Is variants):
//     - GetStatus()        , SetStatus(s)
//     - IsStatusParsed()   , SetStatusParsed()   , UnSetStatusParsed()
//     - IsStatusVendor()   , SetStatusVendor()   , UnSetStatusVendor()
//     - IsStatusAnalyzed() , SetStatusAnalyzed() , UnSetStatusAnalyzed()
//     - IsStatusAudited1() , SetStatusAudited1() , UnSetStatusAudited1()
//     - IsStatusAudited2() , SetStatusAudited2() , UnSetStatusAudited2()
//     - IsStatusAudited3() , SetStatusAudited3() , UnSetStatusAudited3()
//     - IsStatusAudited4() , SetStatusAudited4() , UnSetStatusAudited4()
//     - IsStatusOutdated() , SetStatusOutdated() , UnSetStatusOutdated()
//     - IsStatusNone()     , SetStatusNone()
//   Summary:
//     - GetSummary()       , SetSummary(s)
//   Reports:
//     - GetReports(name)   , SetReports(r)
//     - DelReports(name)   , LstReports()
//   Merge:
//     - Merge(f any)                                : merges another mdl into this entry.

